/*
 * build-cookbook-meals.js  —  dev tooling, run with `node build-cookbook-meals.js`
 *
 * Reads the 6 cookbook cards' #meal-data islands (docs/cookbook/*.html), maps
 * every build to an app Meal Library item {name, calories, protein, carbs, fat,
 * fiber}, and writes cookbook-meals.js — a zero-dependency data file the app
 * loads (window.CookbookMeals). Regenerate whenever the cookbook macros change.
 *
 * Mapping notes:
 *   - cookbook macro key `kcal` → app `calories`; protein/carbs/fat/fiber pass through.
 *   - the cookbook carries no sodium, so imported meals leave it null.
 *   - card slot is "L/D" (not a single app slot), so imported meals carry no slot.
 *   - name = "<meal title> — <build name>".
 *
 * Each mapped meal is validated against the REAL app validator (Logic.validateMealItem)
 * so a bad map fails the build instead of shipping.
 */
'use strict';
var fs = require('fs');
var path = require('path');

var HERE = __dirname;
var COOKBOOK = path.join(HERE, 'docs', 'cookbook');

// Fixed order → stable output diff. (Southwest & Burger have 7 builds; rest 6 → 38.)
var CARDS = [
  'southwest-hybrid-bowl',
  'bbq-power-bowl',
  'loaded-potato-bowl',
  'burger-bowl',
  'italian-bowl',
  'chili-bowl'
];

// Load the app's real validator via a tiny window shim (logic.js sets window.Logic).
global.window = global;
new Function(fs.readFileSync(path.join(HERE, 'logic.js'), 'utf8'))();
var L = global.window.Logic;

function readIsland(slug) {
  var html = fs.readFileSync(path.join(COOKBOOK, slug + '.html'), 'utf8');
  var m = html.match(/<script[^>]*id="meal-data"[^>]*>([\s\S]*?)<\/script>/);
  if (!m) throw new Error('No #meal-data island in ' + slug);
  return JSON.parse(m[1]);
}

var meals = [];
CARDS.forEach(function (slug) {
  var d = readIsland(slug);
  (d.variations || []).forEach(function (v) {
    var mm = v.macros || {};
    meals.push({
      name: d.title + ' — ' + v.name,   // "Southwest Hybrid Protein Bowl — Fajita Chicken"
      calories: Math.round(mm.kcal),
      protein: mm.protein,
      carbs: mm.carbs,
      fat: mm.fat,
      fiber: mm.fiber
    });
  });
});

// ---- validate before writing ----
var problems = [];
if (meals.length !== 38) problems.push('expected 38 builds, got ' + meals.length);
var seen = {};
meals.forEach(function (it) {
  if (seen[it.name]) problems.push('duplicate name: ' + it.name);
  seen[it.name] = true;
  var check = L.validateMealItem(it);
  if (!check.valid) problems.push('invalid meal "' + it.name + '": ' +
    Object.keys(check.errors).map(function (k) { return check.errors[k]; }).join(', '));
  ['calories', 'protein', 'carbs', 'fat', 'fiber'].forEach(function (k) {
    if (typeof it[k] !== 'number' || !isFinite(it[k])) problems.push(it.name + ' has non-numeric ' + k);
  });
});
if (problems.length) {
  console.error('build-cookbook-meals FAILED:\n  ' + problems.join('\n  '));
  process.exit(1);
}

// ---- write cookbook-meals.js ----
var body = meals.map(function (it) {
  return '  { "name": ' + JSON.stringify(it.name) +
    ', "calories": ' + it.calories +
    ', "protein": ' + it.protein +
    ', "carbs": ' + it.carbs +
    ', "fat": ' + it.fat +
    ', "fiber": ' + it.fiber + ' }';
}).join(',\n');

var out =
  '/*\n' +
  ' * cookbook-meals.js — AUTO-GENERATED by build-cookbook-meals.js. Do not edit by hand.\n' +
  ' * The 38 cookbook builds as app Meal Library items (name + 5 macros; no sodium/slot).\n' +
  ' * Regenerate: node build-cookbook-meals.js\n' +
  ' */\n' +
  'window.CookbookMeals = [\n' + body + '\n];\n';

fs.writeFileSync(path.join(HERE, 'cookbook-meals.js'), out);
console.log('Wrote cookbook-meals.js — ' + meals.length + ' meals, all valid.');
